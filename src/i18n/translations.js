// Falls back to English, then to the key itself, so nothing ever renders blank.
export function translate(lang, key, params) {
  const table = translations[lang] || translations[DEFAULT_LANGUAGE];
  let text = table[key];
  if (text === undefined) {
    text = translations[DEFAULT_LANGUAGE][key];
  }
  if (text === undefined) {
    return key;
  }
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (match, name) =>
      params[name] !== undefined && params[name] !== null
        ? String(params[name])
        : match
    );
  }
  return text;
}
